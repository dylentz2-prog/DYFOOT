enum class AppLanguage(val code: String, val displayName: String, val shortBadge: String) {
    ENGLISH("en", "English", "EN"),
    SWAHILI("sw", "Kiswahili", "SW");

    companion object {
        fun fromCode(raw: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(raw, ignoreCase = true) } ?: ENGLISH
    }
}

